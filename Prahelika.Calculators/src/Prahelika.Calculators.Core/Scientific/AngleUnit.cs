namespace Prahelika.Calculators.Core.Scientific;

/// <summary>The unit used for angles in trigonometric functions.</summary>
public enum AngleUnit
{
    /// <summary>Angles are measured in radians (a full circle is 2 * pi).</summary>
    Radians = 0,

    /// <summary>Angles are measured in degrees (a full circle is 360 degrees).</summary>
    Degrees = 1
}